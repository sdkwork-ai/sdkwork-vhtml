/**
 * Caption sidecar generation (WebVTT / SRT).
 */

import fs from 'node:fs';
import path from 'node:path';
import { findTimeline, type CaptionClip, type Project } from '@sdkwork/vhtml-core/model';
import { ZERO, add, formatTimecode, lt, max, min, sub, toNumber, type Rational } from '@sdkwork/vhtml-core/time';

function escapeCue(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/\r\n?/g, '\n');
}

function captionClips(project: Project, timelineId?: string): CaptionClip[] {
  const timeline = findTimeline(project, timelineId ?? project.mainTimeline);
  if (!timeline) return [];
  const clips: CaptionClip[] = [];
  for (const track of timeline.tracks) {
    if (track.type !== 'caption') continue;
    for (const clip of track.clips) {
      if (clip.kind === 'caption' && clip.enabled) clips.push(clip);
    }
  }
  return clips.sort((a, b) => toNumber(a.start) - toNumber(b.start));
}

export function generateWebVtt(
  project: Project,
  timelineId?: string,
  rangeStart: Rational = ZERO,
  rangeDuration?: Rational,
): string {
  const timeline = findTimeline(project, timelineId ?? project.mainTimeline);
  const rangeEnd = rangeDuration ? add(rangeStart, rangeDuration) : timeline?.duration;
  const clips = captionClips(project, timelineId);
  const lines: string[] = ['WEBVTT', '', `NOTE Generated by VHTML 1.1 — project ${project.id}`, ''];
  let index = 0;
  for (const clip of clips) {
    const start = rangeEnd ? max(clip.start, rangeStart) : clip.start;
    const end = rangeEnd ? min(add(clip.start, clip.duration), rangeEnd) : add(clip.start, clip.duration);
    if (rangeEnd && !lt(start, end)) continue;
    index += 1;
    const relativeStart = sub(start, rangeStart);
    const relativeEnd = sub(end, rangeStart);
    lines.push(String(index));
    lines.push(`${formatTimecode(relativeStart)} --> ${formatTimecode(relativeEnd)}`);
    const text = escapeCue(clip.text);
    lines.push(clip.speaker ? `<v ${escapeCue(clip.speaker)}>${text}` : text);
    lines.push('');
  }
  return lines.join('\n');
}

export function generateSrt(
  project: Project,
  timelineId?: string,
  rangeStart: Rational = ZERO,
  rangeDuration?: Rational,
): string {
  const timeline = findTimeline(project, timelineId ?? project.mainTimeline);
  const rangeEnd = rangeDuration ? add(rangeStart, rangeDuration) : timeline?.duration;
  const clips = captionClips(project, timelineId);
  const lines: string[] = [];
  let index = 0;
  for (const clip of clips) {
    const start = rangeEnd ? max(clip.start, rangeStart) : clip.start;
    const end = rangeEnd ? min(add(clip.start, clip.duration), rangeEnd) : add(clip.start, clip.duration);
    if (rangeEnd && !lt(start, end)) continue;
    index += 1;
    lines.push(String(index));
    lines.push(`${formatTimecode(sub(start, rangeStart), ',')} --> ${formatTimecode(sub(end, rangeStart), ',')}`);
    lines.push(escapeCue(clip.text).replace(/<[^>]+>/g, ''));
    lines.push('');
  }
  return lines.join('\n');
}

export function writeCaptions(
  project: Project,
  file: string,
  options: { timelineId?: string; rangeStart?: Rational; rangeDuration?: Rational; format?: 'vtt' | 'srt' } = {},
): string {
  const target = path.resolve(file);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  const format = options.format ?? (target.toLowerCase().endsWith('.srt') ? 'srt' : 'vtt');
  const text =
    format === 'srt'
      ? generateSrt(project, options.timelineId, options.rangeStart, options.rangeDuration)
      : generateWebVtt(project, options.timelineId, options.rangeStart, options.rangeDuration);
  fs.writeFileSync(target, text, 'utf8');
  return target;
}

export function cueCount(project: Project, timelineId?: string): number {
  return captionClips(project, timelineId).length;
}

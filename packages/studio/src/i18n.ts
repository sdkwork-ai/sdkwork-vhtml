export const STUDIO_LOCALES: Record<StudioLanguage, Record<string, string>> = {
  en,
  'zh-CN': zh,
};

/** Resolve the Studio language for a browser-like environment. */
export function detectStudioLanguage(navigatorLanguage: string | undefined, stored: string | null): StudioLanguage {
  if (stored === 'zh-CN' || stored === 'en') return stored;
  if (navigatorLanguage && navigatorLanguage.toLowerCase().startsWith('zh')) return 'zh-CN';
  return 'en';
}
